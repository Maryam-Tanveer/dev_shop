/**
 * Normalize country input string and find matching state list
 */
export function getStatesForCountry(country) {
  if (!country) return []
  const norm = String(country).trim().toLowerCase()

  if (norm === 'pk' || norm === 'pak' || norm === 'pakistan') {
    return STATES_BY_COUNTRY.pakistan
  }
  if (norm === 'us' || norm === 'usa' || norm === 'united states' || norm === 'united states of america') {
    return STATES_BY_COUNTRY['united states']
  }
  if (norm === 'ca' || norm === 'can' || norm === 'canada') {
    return STATES_BY_COUNTRY.canada
  }
  if (norm === 'uk' || norm === 'gb' || norm === 'united kingdom' || norm === 'great britain') {
    return STATES_BY_COUNTRY['united kingdom']
  }
  if (norm === 'ae' || norm === 'uae' || norm === 'united arab emirates') {
    return STATES_BY_COUNTRY['united arab emirates']
  }
  if (norm === 'sa' || norm === 'ksa' || norm === 'saudi arabia') {
    return STATES_BY_COUNTRY['saudi arabia']
  }
  if (norm === 'au' || norm === 'aus' || norm === 'australia') {
    return STATES_BY_COUNTRY.australia
  }
  if (norm === 'in' || norm === 'ind' || norm === 'india') {
    return STATES_BY_COUNTRY.india
  }
  if (norm === 'de' || norm === 'germany' || norm === 'deutschland') {
    return STATES_BY_COUNTRY.germany
  }
  if (norm === 'fr' || norm === 'france') {
    return STATES_BY_COUNTRY.france
  }
  if (norm === 'tr' || norm === 'turkey' || norm === 'türkiye') {
    return STATES_BY_COUNTRY.turkey
  }
  if (norm === 'my' || norm === 'malaysia') {
    return STATES_BY_COUNTRY.malaysia
  }

  return STATES_BY_COUNTRY[norm] || []
}
